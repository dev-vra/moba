import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--ignore-gpu-blocklist', '--enable-gpu', '--use-angle=d3d11'] });
const p = await b.newPage(); await p.setViewport({ width: 1600, height: 900 });
p.on('pageerror', (e) => console.log('[pageerror]', e.message)); p.on('console', (m) => m.type() === 'error' && console.log('[err]', m.text()));
await p.goto(`http://localhost:${process.env.PORT || 5179}/`); await new Promise((r) => setTimeout(r, 3500));
await p.screenshot({ path: 'shots/menu_title.jpg', type: 'jpeg', quality: 82 });
await p.click('[data-a=play]'); await new Promise((r) => setTimeout(r, 2500));
await p.screenshot({ path: 'shots/menu_select.jpg', type: 'jpeg', quality: 82 });
await p.click('.go'); await new Promise((r) => setTimeout(r, 900));
await p.screenshot({ path: 'shots/menu_loading.jpg', type: 'jpeg', quality: 82 });
await p.waitForFunction('window.__ready', { timeout: 60000 }); console.log('game ready, hero', await p.evaluate(() => __g.hero.kit.id));
await b.close();
